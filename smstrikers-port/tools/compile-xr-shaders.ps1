# strikers-quest: compiles src/platform/shaders/*.vert|*.frag to SPIR-V with the NDK's glslc and
# writes them as uint32_t arrays into src/platform/xr_fx_shaders.h (checked in, so the CMake build
# needs no shader compiler). Re-run after editing a shader.
#   powershell -File tools\compile-xr-shaders.ps1 -Glslc <path to glslc.exe>
param([Parameter(Mandatory = $true)][string]$Glslc)
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$src = Join-Path $root 'src\platform\shaders'
$out = Join-Path $root 'src\platform\xr_fx_shaders.h'
$tmp = Join-Path $env:TEMP 'strikers-xr-shaders'
New-Item -ItemType Directory -Force $tmp | Out-Null

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tools/compile-xr-shaders.ps1 from src/platform/shaders. Do not edit.')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('#include <stdint.h>')
foreach ($f in Get-ChildItem $src -File | Where-Object { $_.Extension -in '.vert', '.frag' } | Sort-Object Name) {
    $spv = Join-Path $tmp ($f.Name + '.spv')
    & $Glslc -O --target-env=vulkan1.0 -o $spv $f.FullName
    if ($LASTEXITCODE -ne 0) { throw "glslc failed on $($f.Name)" }
    $bytes = [IO.File]::ReadAllBytes($spv)
    $name = 'k' + (($f.BaseName -split '_' | ForEach-Object { $_.Substring(0, 1).ToUpper() + $_.Substring(1) }) -join '') +
        $(if ($f.Extension -eq '.vert') { 'Vert' } else { 'Frag' })
    [void]$sb.AppendLine("static const uint32_t ${name}[] = {")
    $words = New-Object System.Collections.Generic.List[string]
    for ($i = 0; $i -lt $bytes.Length; $i += 4) {
        $words.Add(('0x{0:x8}u' -f [BitConverter]::ToUInt32($bytes, $i)))
    }
    for ($i = 0; $i -lt $words.Count; $i += 8) {
        [void]$sb.AppendLine('    ' + (($words.GetRange($i, [Math]::Min(8, $words.Count - $i))) -join ', ') + ',')
    }
    [void]$sb.AppendLine('};')
}
[IO.File]::WriteAllText($out, $sb.ToString().Replace("`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))
"wrote $out"
